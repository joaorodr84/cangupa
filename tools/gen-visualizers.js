#!/usr/bin/env node
// Builds tools/visualizers/level-packs.html and level-difficulty.html by inlining the real
// pack data (tools/packs.json) into the two *.template.html files in tools/visualizers/, so
// the pages open straight from disk (file://) with no server and no fetch() of a sibling
// JSON file. gen-packs.js calls writeVisualizers() itself at the end of every run, so the
// two pages are regenerated automatically whenever the level packs change; run this file
// directly only to refresh them from an already-written tools/packs.json without redoing
// gen-packs.js's (slow) measuring pass.
//
//   node tools/gen-visualizers.js
const fs = require('fs');
const path = require('path');

const DIR = __dirname;
const VIS = path.join(DIR, 'visualizers');
const PLACEHOLDER = '/*GEN:PACKS_JSON*/';
const PAGES = ['level-packs', 'level-difficulty'];

function render(packs) {
  // "</script" inside a string would otherwise close the data tag early.
  const json = JSON.stringify({ packs }).replace(/<\/script/gi, '<\\/script');
  for (const page of PAGES) {
    const template = fs.readFileSync(path.join(VIS, `${page}.template.html`), 'utf8');
    if (!template.includes(PLACEHOLDER)) throw new Error(`${page}.template.html is missing ${PLACEHOLDER}`);
    const html = `<!-- Generated by tools/gen-visualizers.js from tools/packs.json. Do not edit by hand; edit ${page}.template.html instead. -->\n`
      + template.replace(PLACEHOLDER, json);
    fs.writeFileSync(path.join(VIS, `${page}.html`), html);
  }
}

function writeVisualizers(packs) {
  render(packs);
  console.log(`wrote tools/visualizers/{${PAGES.join(',')}}.html`);
}

if (require.main === module) {
  const { packs } = JSON.parse(fs.readFileSync(path.join(DIR, 'packs.json'), 'utf8'));
  writeVisualizers(packs);
}

module.exports = { writeVisualizers };
